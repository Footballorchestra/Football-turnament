/**
 * Выход страницы из чужого iframe (защита от встраивания сайта).
 *
 * Заголовки ответа на GitHub Pages задать нельзя, а директива CSP `frame-ancestors`
 * в теге <meta> не работает: браузеры её там игнорируют. Поэтому страница сама
 * проверяет, не открыта ли она внутри фрейма, и просит верхнее окно перейти на свой
 * адрес. На Netlify и Cloudflare Pages тот же запрет добавлен жёстко — заголовками
 * из файла _headers (X-Frame-Options и frame-ancestors).
 */
(function () {
    'use strict';

    if (window.top === window.self) {
        return; // страница открыта напрямую — ничего не делаем
    }

    try {
        window.top.location = window.self.location.href;
    } catch (error) {
        // Чужой сайт запретил навигацию верхнего окна: выйти из фрейма нельзя,
        // страница просто работает дальше как обычно.
    }
}());
